import type {
    CatalogRecipe,
    RecipeIngredient,
} from '../types/recipe';

export const RECIPE_CATALOG_VERSION = '2026.07.1';

type RecipeSeed = Omit<CatalogRecipe, 'ingredients' | 'usedIngredients' | 'prepTime' | 'cookTime'>;

function food(name: string, amount: string, aliases?: string[]): RecipeIngredient {
    return { name, amount, ...(aliases ? { aliases } : {}) };
}

function staple(name: string, amount: string): RecipeIngredient {
    return { name, amount, pantryStaple: true };
}

function optional(name: string, amount: string, aliases?: string[]): RecipeIngredient {
    return { name, amount, optional: true, ...(aliases ? { aliases } : {}) };
}

function defineRecipe(seed: RecipeSeed): CatalogRecipe {
    const formatTime = (minutes: number) => minutes + (minutes === 1 ? ' min' : ' mins');
    return {
        ...seed,
        ingredients: seed.ingredientDetails.map(ingredient => (
            (ingredient.amount + ' ' + ingredient.name).trim()
        )),
        usedIngredients: seed.ingredientDetails
            .filter(ingredient => !ingredient.pantryStaple && !ingredient.optional)
            .map(ingredient => ingredient.name),
        prepTime: formatTime(seed.prepMinutes),
        cookTime: formatTime(seed.cookMinutes),
    };
}

